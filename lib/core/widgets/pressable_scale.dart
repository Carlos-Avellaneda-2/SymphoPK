import 'package:flutter/material.dart';

/// Microinteracción: encoge ligeramente su hijo mientras se mantiene pulsado.
/// No intercepta el gesto, así que el botón interior sigue recibiendo el tap.
class PressableScale extends StatefulWidget {
  const PressableScale({super.key, required this.child, this.scale = 0.9});

  final Widget child;
  final double scale;

  @override
  State<PressableScale> createState() => _PressableScaleState();
}

class _PressableScaleState extends State<PressableScale> {
  bool _pressed = false;

  void _set(bool pressed) {
    if (_pressed != pressed) setState(() => _pressed = pressed);
  }

  @override
  Widget build(BuildContext context) {
    return Listener(
      onPointerDown: (_) => _set(true),
      onPointerUp: (_) => _set(false),
      onPointerCancel: (_) => _set(false),
      child: AnimatedScale(
        scale: _pressed ? widget.scale : 1,
        duration: const Duration(milliseconds: 110),
        curve: Curves.easeOut,
        child: widget.child,
      ),
    );
  }
}
